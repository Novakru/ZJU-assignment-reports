"""Order numbered references by first citation while preserving source metadata."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parent

def expand(source):
    def sub(m):
        name=m.group(1)
        if name in ('metadata.tex','review-references.tex'):return ''
        return expand((ROOT/name).read_text(encoding='utf-8'))
    return re.sub(r'\\input\{([^}]+)\}',sub,source)

if __name__=='__main__':
    records=(ROOT/'reference-records.tex').read_text(encoding='utf-8')
    records=re.sub(r'^%.*$','',records,flags=re.M)
    items={m.group(1):m.group(0).strip() for m in re.finditer(r'\\bibitem\{([^}]+)\}.*?(?=\\bibitem|\Z)',records,re.S)}
    source=expand((ROOT/'review.tex').read_text(encoding='utf-8'))
    order=[]
    for group in re.findall(r'\\cite\{([^}]+)\}',source):
        for key in group.split(','):
            assert key in items,key
            if key not in order:order.append(key)
    assert len(order)==len(items) and set(order)==set(items),(order,list(items))
    header=r'''% Generated by format_references.py; edit reference-records.tex.
\begingroup\fontsize{9.5}{12.5}\selectfont\raggedright\urlstyle{same}
\interlinepenalty=10000
\begin{thebibliography}{99}
\setlength{\itemsep}{0pt}\setlength{\parsep}{0pt}
\interlinepenalty=10000
'''
    footer=r'''
\end{thebibliography}
\endgroup
'''
    (ROOT/'review-references.tex').write_text(header+'\n'.join(items[k] for k in order)+footer,encoding='utf-8')
    print('Numbered references:',len(order))
